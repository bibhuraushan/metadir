#!/bin/zsh

set -euo pipefail
setopt extended_glob

project_root="${0:A:h:h}"
config_file="$project_root/LocalMonitoredRoots.yml"
swift_file="$project_root/MetaDirFinderSync/GeneratedLocalRoots.swift"
entitlements_file="$project_root/MetaDirFinderSync/MetaDirFinderSync.entitlements"

if [[ ! -f "$config_file" ]]; then
    print -u2 "Missing configuration: $config_file"
    exit 1
fi

roots=()
while IFS= read -r line; do
    value="${line#*-}"
    value="${value##[[:space:]]#}"
    value="${value%%[[:space:]]#}"
    value="${value#\"}"
    value="${value%\"}"
    value="${value#\'}"
    value="${value%\'}"
    [[ "$value" == /* ]] || continue
    [[ -d "$value" ]] || { print -u2 "Configured root is not a directory: $value"; exit 1; }
    [[ "$value" == */ ]] || value="$value/"
    roots+=("$value")
done < <(grep -E '^[[:space:]]*-[[:space:]]*/' "$config_file" || true)

if (( ${#roots} == 0 )); then
    print -u2 "LocalMonitoredRoots.yml must contain at least one absolute directory path."
    exit 1
fi

swift_temp="$(mktemp /private/tmp/MetaDirRoots.swift.XXXXXX)"
entitlements_temp="$(mktemp /private/tmp/MetaDirEntitlements.plist.XXXXXX)"

{
    print '// Generated by Scripts/configure-local-roots.sh. Do not edit directly.'
    print 'import Foundation'
    print ''
    print 'enum GeneratedLocalRoots {'
    print '    static let urls: Set<URL> = ['
    for root in "${roots[@]}"; do
        escaped="${root//\\/\\\\}"
        escaped="${escaped//\"/\\\"}"
        print "        URL(fileURLWithPath: \"$escaped\", isDirectory: true),"
    done
    print '    ]'
    print '}'
} > "$swift_temp"

{
    print '<?xml version="1.0" encoding="UTF-8"?>'
    print '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">'
    print '<plist version="1.0">'
    print '<dict>'
    print '    <key>com.apple.security.app-sandbox</key>'
    print '    <true/>'
    print '    <key>com.apple.security.temporary-exception.files.absolute-path.read-only</key>'
    print '    <array>'
    for root in "${roots[@]}"; do
        xml="${root//&/&amp;}"
        xml="${xml//</&lt;}"
        xml="${xml//>/&gt;}"
        print "        <string>$xml</string>"
    done
    print '    </array>'
    print '</dict>'
    print '</plist>'
} > "$entitlements_temp"

plutil -lint "$entitlements_temp" >/dev/null
mv "$swift_temp" "$swift_file"
mv "$entitlements_temp" "$entitlements_file"
print "Configured ${#roots} local Finder root(s)."
